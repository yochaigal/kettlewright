def generator_labels():
    labels = {key: translate_term(value, context) for key, (context, value) in TERMS.items()}
    # Equipment remains keyed by its English identity in the generator data.
    from app.lib.data import load_market
    for item in load_market():
        labels['equipment:' + item['name']] = translate_term(item['name'], 'equipment')
        for tag in item.get('tags', ()):
            labels[tag] = _(tag)
    return labels
